#!/usr/bin/env node
// Generates packages/<plugin>/.goreleaser.yml for every plugin from its metadata.yaml.
//
// Build targets come from metadata.yaml `platforms.<os>.architectures`, so a plugin's
// release assets always match what the registry advertises for it.
//
// Usage:
//   node scripts/release/generate-goreleaser.mjs          # write configs
//   node scripts/release/generate-goreleaser.mjs --check  # exit 1 if any config is stale
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const packagesDir = path.join(repoRoot, "packages");
const NON_PLUGINS = new Set(["plugin-sdk"]);
const SUPPORTED_OS = ["linux", "darwin", "windows"];
const SUPPORTED_ARCH = ["amd64", "arm64"];
const DEFAULT_ARCH = ["amd64", "arm64"];

export function pluginDirs() {
	return readdirSync(packagesDir, { withFileTypes: true })
		.filter((d) => d.isDirectory() && !NON_PLUGINS.has(d.name))
		.map((d) => d.name)
		.filter((name) => existsSync(path.join(packagesDir, name, "metadata.yaml")))
		.sort();
}

export function targetsFromMetadata(name, metadata) {
	const platforms = metadata?.platforms ?? {};
	const targets = [];
	for (const [os, spec] of Object.entries(platforms)) {
		if (!SUPPORTED_OS.includes(os)) {
			throw new Error(`${name}: unsupported platform "${os}" in metadata.yaml (use ${SUPPORTED_OS.join(", ")})`);
		}
		const arches = spec?.architectures?.length ? spec.architectures : DEFAULT_ARCH;
		for (const arch of arches) {
			if (!SUPPORTED_ARCH.includes(arch)) {
				throw new Error(`${name}: unsupported architecture "${arch}" for ${os} in metadata.yaml`);
			}
			targets.push({ os, arch });
		}
	}
	if (targets.length === 0) {
		throw new Error(`${name}: metadata.yaml declares no platforms`);
	}
	return targets;
}

export function renderConfig(name, targets) {
	const goos = SUPPORTED_OS.filter((os) => targets.some((t) => t.os === os));
	const goarch = SUPPORTED_ARCH.filter((arch) => targets.some((t) => t.arch === arch));
	const ignore = [];
	for (const os of goos) {
		for (const arch of goarch) {
			if (!targets.some((t) => t.os === os && t.arch === arch)) ignore.push({ os, arch });
		}
	}

	const binary = `devex-plugin-${name}`;
	const list = (items, indent) => items.map((i) => `${" ".repeat(indent)}- ${i}`).join("\n");
	const ignoreBlock = ignore.length
		? `\n    ignore:\n${ignore.map((i) => `      - goos: ${i.os}\n        goarch: ${i.arch}`).join("\n")}`
		: "";

	return `# Code generated by scripts/release/generate-goreleaser.mjs. DO NOT EDIT.
# Targets come from packages/${name}/metadata.yaml; edit that file and run
#   pnpm release:generate
# yaml-language-server: $schema=https://goreleaser.com/static/schema-pro.json
version: 2
project_name: ${binary}
monorepo:
  tag_prefix: packages/${name}/v
  dir: packages/${name}
metadata:
  mod_timestamp: "{{ .CommitTimestamp }}"
builds:
  - id: ${name}
    main: .
    binary: ${binary}
    env:
      - CGO_ENABLED=0
    flags:
      - -trimpath
    goos:
${list(goos, 6)}
    goarch:
${list(goarch, 6)}${ignoreBlock}
    ldflags:
      - -s -w
      - -X main.version={{ .Version }}
      - -X main.commit={{ .Commit }}
      - -X main.date={{ .CommitDate }}
    mod_timestamp: "{{ .CommitTimestamp }}"
archives:
  # Archive for people downloading from GitHub; SDK v0.0.6+ extracts it.
  - id: archive
    ids: [${name}]
    formats: [tar.gz]
    format_overrides:
      - goos: windows
        formats: [zip]
    name_template: "${binary}_{{ .Version }}_{{ .Os }}_{{ .Arch }}"
    files:
      - README*
      - LICENSE*
  # Raw executable the registry points at; older CLIs install it without extracting.
  - id: binary
    ids: [${name}]
    formats: [binary]
    name_template: "${binary}_{{ .Version }}_{{ .Os }}_{{ .Arch }}"
checksum:
  name_template: checksums.txt
  algorithm: sha256
signs:
  - id: cosign
    cmd: cosign
    artifacts: checksum
    signature: "\${artifact}.sigstore.json"
    args:
      - sign-blob
      - "--bundle=\${signature}"
      - "\${artifact}"
      - --yes
snapshot:
  version_template: "{{ incpatch .Version }}-next"
changelog:
  use: github
  sort: asc
  filters:
    exclude:
      - "^docs:"
      - "^test:"
      - "^chore:"
      - "^ci:"
  groups:
    - title: New Features
      regexp: '^.*?feat(\\([[:word:]-]+\\))??!?:.+$'
      order: 0
    - title: Bug Fixes
      regexp: '^.*?fix(\\([[:word:]-]+\\))??!?:.+$'
      order: 1
    - title: Others
      order: 999
release:
  github:
    owner: jameswlane
    name: devex
  name_template: "${binary} v{{ .Version }}"
  # Only CLI releases may become GitHub's "Latest" release.
  make_latest: false
  prerelease: auto
  preflight:
    fail_on_error: true
verify:
  commands:
    - cmd: sha256sum
      args: ["--ignore-missing", "-c", "checksums.txt"]
    - cmd: cosign
      args:
        - verify-blob
        - --bundle=checksums.txt.sigstore.json
        - --certificate-identity-regexp=^https://github\\.com/jameswlane/devex/\\.github/workflows/
        - --certificate-oidc-issuer=https://token.actions.githubusercontent.com
        - checksums.txt
  retry:
    attempts: 5
    delay: 10s
`;
}

function main() {
	const check = process.argv.includes("--check");
	const stale = [];

	for (const name of pluginDirs()) {
		const dir = path.join(packagesDir, name);
		const metadata = yaml.load(readFileSync(path.join(dir, "metadata.yaml"), "utf8"));
		if (metadata?.name && metadata.name !== name) {
			throw new Error(`${name}: metadata.yaml name "${metadata.name}" does not match its directory`);
		}
		const config = renderConfig(name, targetsFromMetadata(name, metadata));
		const target = path.join(dir, ".goreleaser.yml");
		const current = existsSync(target) ? readFileSync(target, "utf8") : "";

		if (current === config) continue;
		if (check) {
			stale.push(path.relative(repoRoot, target));
		} else {
			writeFileSync(target, config);
			console.log(`wrote ${path.relative(repoRoot, target)}`);
		}
	}

	if (stale.length) {
		console.error("GoReleaser configs are out of date; run `pnpm release:generate`:");
		for (const file of stale) console.error(`  ${file}`);
		process.exit(1);
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	main();
}
